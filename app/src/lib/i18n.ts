export type I18nKey = keyof typeof az;

/**
 * A locale's strings: every az key, plus any plural form.
 *
 * The plural escape hatch exists because languages do not agree on how many forms there are.
 * Azerbaijani keeps the singular after a numeral, so az declares only `app.plural.fields.other` —
 * and if I18nKey were the whole of Dict, Russian could not declare the three forms its grammar
 * requires. tp() reads these at runtime through tf(), which takes plain strings.
 */
type PluralForms = { [K in `app.plural.${string}`]?: string };
export type Dict = Partial<Record<I18nKey, string>> & PluralForms;

// Phase 4 / P1.1 — 8 locales. az is the complete source of truth; the rest fall back to az for any
// missing key. Translations live in lib/locales/{en,ru,tr,de,hu,it,pl}.ts. ru is a launch-tier
// language (the working lingua franca of agriculture across the South Caucasus and Central Asia),
// held to the same quality bar as az — not a machine-translated afterthought.
export type Locale = "az" | "en" | "ru" | "tr" | "de" | "hu" | "it" | "pl";
export const LOCALES: Locale[] = ["az", "en", "ru", "tr", "de", "hu", "it", "pl"];
export const LOCALE_NAMES: Record<Locale, string> = {
  az: "Azərbaycan", en: "English", ru: "Русский", tr: "Türkçe", de: "Deutsch",
  hu: "Magyar", it: "Italiano", pl: "Polski",
};

// Registered lazily by LocaleProvider so this module has no import cycle with the big dicts.
const DICTS: Partial<Record<Locale, Dict>> = { az };
export function registerDict(locale: Locale, dict: Dict): void {
  DICTS[locale] = dict;
}

// Client-side current locale (per browser). SSR renders in az; the client sets the real locale in
// LocaleProvider before the app's (client-gated) content renders, so visible text is correct.
let _locale: Locale = "az";
export function setLocale(l: Locale): void {
  if (LOCALES.includes(l)) _locale = l;
}
export function getLocale(): Locale {
  return _locale;
}

/** Best locale for a first-time visitor: explicit cookie/localStorage → browser language → az. */
export function detectLocale(): Locale {
  try {
    const stored = (localStorage.getItem("bagban_locale") || "") as Locale;
    if (LOCALES.includes(stored)) return stored;
    const nav = (navigator.language || "").slice(0, 2).toLowerCase() as Locale;
    if (LOCALES.includes(nav)) return nav;
  } catch { /* SSR / private mode */ }
  return "az";
}

export function t(key: I18nKey): string {
  const d = DICTS[_locale];
  return (d && d[key]) || az[key] || (key as string);
}

/**
 * Like t(), but interpolates {placeholder} tokens in the resolved string with String(params[name]).
 * Used to render backend-generated, machine-coded prose (wellness/pest/weather reasons) in the
 * active locale — the codes + raw params come from the API, the sentence template lives here.
 * Unmatched tokens are left intact. Accepts any key string (backend codes map to app.* keys that
 * exist in the dictionaries but are not all in the I18nKey union at authoring time).
 */
export function tf(key: string, params?: Record<string, unknown>): string {
  const d = DICTS[_locale] as unknown as Record<string, string> | undefined;
  const azAny = az as unknown as Record<string, string>;
  const raw = (d && d[key]) || azAny[key] || key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m,
  );
}

/**
 * The noun form that agrees with `n` in the active locale: tp("app.plural.fields", 1).
 *
 * A count and a fixed noun cannot simply be concatenated once there is more than one language in
 * the product. Azerbaijani and Turkish keep the singular after any numeral ("5 sahə"), English and
 * German need one/other, and Russian and Polish need three forms — which is how "1 полей" reached
 * the field list. Intl.PluralRules knows every one of those rules, so the dictionaries only supply
 * the forms: `<base>.one|few|many|other`, with `.other` as the fallback every locale must have.
 */
export function tp(base: string, n: number): string {
  let cat = "other";
  try {
    cat = new Intl.PluralRules(_locale).select(n);
  } catch {
    /* unknown locale tag — `other` is the safe form */
  }
  const exact = tf(`${base}.${cat}`);
  return exact === `${base}.${cat}` ? tf(`${base}.other`) : exact;
}
